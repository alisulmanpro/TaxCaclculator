interface ExploreCalculatorsSectionProps {
  categories?: ToolCategory[];
  eyebrow?: string;
  title?: string;
  description?: string;
}

/**
 * Reusable Explore Calculators Section.
 * Placed immediately after the FAQ section on both Single-Year and Multi-Year calculator pages.
 * Category grouping with wallet icon and a card for each available calculator.
 */
export default function ExploreCalculatorsSection({
  categories = toolCategories,
  eyebrow = "EXPLORE OUR TOOLS",
  title = "Explore Our Tax Calculators",
  description = "Choose the right calculator for your salary and income decisions. Explore our tools to calculate your tax with confidence.",
}: ExploreCalculatorsSectionProps) {
  return (
    <section className="fx-section" id="explore-calculators" aria-labelledby="explore-calculators-title">
      <div className="fx-wrap fx-stack scroll-reveal">
        <SectionHeader
          eyebrow={eyebrow}
          icon={
            <svg
              width="14"
              height="14"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2.2"
              strokeLinecap="round"
              strokeLinejoin="round"
              aria-hidden="true"
            >
              <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z" />
            </svg>
          }
          title={title}
          titleId="explore-calculators-title"
          lead={description}
        />

        {/* Directory Container */}
        <div className="fx-stack">
          {categories.map((category) => {
            const count = category.tools.length;
            const countLabel = `${count} ${count === 1 ? "Calculator" : "Calculators"}`;

            return (
              <div key={category.id} className="tools-category">
                {/* Category Header */}
                <div className="tools-category-header">
                  <div className="tools-category-title-group">
                    <span className="tools-category-dot" aria-hidden="true" />
                    <span className="tools-category-icon" aria-hidden="true">
                      <CategoryIcon icon={category.icon} />
                    </span>
                    <h3 className="tools-category-name">{category.name}</h3>
                  </div>

                  <div className="tools-category-divider" aria-hidden="true" />

                  <span className="tools-category-badge">{countLabel}</span>
                </div>

                {/* Cards Grid */}
                <div className="tools-grid">
                  {category.tools.map((tool) => (
                    <Link
                      key={tool.id}
                      href={tool.href}
                      className="tool-card"
                      aria-label={`${tool.name} — ${tool.description}`}
                    >
                      <div className="tool-card-icon-wrap" aria-hidden="true">
                        <ToolIcon icon={tool.icon} />
                      </div>

                      <div className="tool-card-content">
                        <div className="tool-card-title-row">
                          <span className="tool-card-title">{tool.name}</span>
                          {tool.badge && (
                            <span className="tool-card-badge">{tool.badge}</span>
                          )}
                        </div>
                        <p className="tool-card-desc">{tool.description}</p>
                      </div>

                      <div className="tool-card-chevron" aria-hidden="true">
                        <svg
                          width="18"
                          height="18"
                          viewBox="0 0 24 24"
                          fill="none"
                          stroke="currentColor"
                          strokeWidth="2.2"
                          strokeLinecap="round"
                          strokeLinejoin="round"
                        >
                          <polyline points="9 18 15 12 9 6" />
                        </svg>
                      </div>
                    </Link>
                  ))}
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
